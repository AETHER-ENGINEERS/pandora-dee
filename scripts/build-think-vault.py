#!/usr/bin/env python3
"""Assemble the vault-resident version of the think tool.

The in-app tool (app/modules/think_tool.js) and the vault script share one engine: this script cuts the pure
engine out of the module (between the ENGINE markers) and wraps it with the vault/CLI half in app/vault/think_cli.js.
Output mirrors a vault, so unzipping into the vault root puts every file where Jade looks for it:

    dist/think-vault/Jade/tools/think.js
    dist/think-vault/Jade/skills/think-before-acting/SKILL.md
    dist/think-vault.zip

Works on any app version that has the node shell and the jade object (2.x), with no app update.
"""
import os, re, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda *p: open(os.path.join(ROOT, *p), encoding='utf-8').read()

mod = rd('app', 'modules', 'think_tool.js')
i, j = mod.index('/*ENGINE:BEGIN*/'), mod.index('/*ENGINE:END*/')
engine = mod[i + len('/*ENGINE:BEGIN*/'):j]
for bad in ('vfs.', 'decideData', 'askOnce', 'runNodeScript', 'window.', 'document.', 'S.'):
    if re.search(r'(?<![A-Za-z_$])' + re.escape(bad), engine):
        sys.exit(f'the shared engine must not use {bad!r} (it has to run outside the app too)')

cli = rd('app', 'vault', 'think_cli.js')
assert cli.count('/*@ENGINE@*/') == 1
version = rd('VERSION').strip()
header = f"""// think.js (Jade Vault {version}) — a tree of thoughts with verification, as a vault script.
//
//   node /Jade/tools/think.js help
//   node /Jade/tools/think.js <action> '<json>'      (or @file.json, or key=value)
//
// Branch several lines of reasoning, check each with something that can say no (run code, find a file, a rubric, an
// independent judge), and answer with the best VERIFIED line. State lives in /Jade/Tot. Generated by
// scripts/build-think-vault.py: the engine between the markers below is shared with the in-app tool.
// ---- shared engine (generated) ----------------------------------------------------------------------------------
"""
script = header + engine.strip('\n') + '\n// ---- vault half ----------------------------------------------------------------------------------------------\n' + cli.replace('/*@ENGINE@*/\n', '')

out = os.path.join(ROOT, 'dist', 'think-vault')
shutil.rmtree(out, ignore_errors=True)
files = {
    'Jade/tools/think.js': script,
    'Jade/skills/think-before-acting/SKILL.md': rd('app', 'vault', 'skills', 'think-before-acting', 'SKILL.md'),
}
for rel, text in files.items():
    p = os.path.join(out, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w', encoding='utf-8').write(text)
z = os.path.join(ROOT, 'dist', 'think-vault.zip')
with zipfile.ZipFile(z, 'w', zipfile.ZIP_DEFLATED) as zf:
    for rel in files: zf.write(os.path.join(out, rel), rel)
print('ok', {k: len(v) for k, v in files.items()}, '->', os.path.relpath(z, ROOT))
